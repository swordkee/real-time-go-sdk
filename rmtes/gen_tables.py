#!/usr/bin/env python3
"""从 LSEG Real-Time-SDK 的 rsslcnvtab.c 机械转写 RMTES→UCS2 转换表为 Go 源码。

来源（Apache-2.0，Copyright (C) 2018-2019,2024 LSEG）：
  Cpp-C/Eta/Impl/Codec/rsslcnvtab.c  （上游 commit 7d219a600）
本脚本与产物 tables.go 一并入库，便于日后表升级时重跑核对。

用法：
  python3 gen_tables.py [rsslcnvtab.c 路径]
默认从环境变量 RMTES_C_TABLE 或内置默认路径读取。
输出写到本脚本同目录的 tables.go。
"""

import os
import re
import sys

DEFAULT_TABLE = (
    r"E:\work\lsmall\Real-Time-SDK\Cpp-C\Eta\Impl\Codec\rsslcnvtab.c"
)

# 期望的表规模，来自 rsslCharSet.c 的 RsslRmtesCharSet 定义。
# 用于自检：C 表行数与 C 代码声明的长度必须一致，否则拒绝生成（fail-closed）。
EXPECTED = {
    "rsslcnvtab_rbcs2": 94,
    "rsslcnvtab_rbcs2_br": 94,
    "rsslcnvtab_romaji": 94,
    "rsslcnvtab_katakana": 94,
    "rsslcnvtab_208a": 690,
    "rsslcnvtab_208b": 6398,
    "rsslcnvtab_cns1a": 500,
    "rsslcnvtab_cns1b": 5589,
    "rsslcnvtab_cns2": 7650,
}

GO_NAMES = {
    "rsslcnvtab_rbcs2": "tblRBCS2",
    "rsslcnvtab_rbcs2_br": "tblRBCS2BR",
    "rsslcnvtab_romaji": "tblRomaji",
    "rsslcnvtab_katakana": "tblKatakana",
    "rsslcnvtab_208a": "tbl208a",
    "rsslcnvtab_208b": "tbl208b",
    "rsslcnvtab_cns1a": "tblCNS1a",
    "rsslcnvtab_cns1b": "tblCNS1b",
    "rsslcnvtab_cns2": "tblCNS2",
}

BLOCK = re.compile(
    r"rssl_uni_map_entry\s+(\w+)\s*\[\]\s*=\s*\{(.*?)\};", re.S
)
HEX = re.compile(r"0x[0-9A-Fa-f]+")


def main():
    path = os.environ.get("RMTES_C_TABLE") or (sys.argv[1] if len(sys.argv) > 1 else DEFAULT_TABLE)
    with open(path, encoding="utf-8", errors="replace") as fh:
        src = fh.read()

    tables = {}
    for m in BLOCK.finditer(src):
        name = m.group(1)
        vals = [int(v, 16) for v in HEX.findall(m.group(2))]
        if name in EXPECTED:
            if len(vals) != EXPECTED[name]:
                raise SystemExit(
                    f"表 {name} 条目数 {len(vals)} != 期望 {EXPECTED[name]}，拒绝生成"
                )
            tables[name] = vals
    missing = set(EXPECTED) - set(tables)
    if missing:
        raise SystemExit(f"缺少 C 表: {sorted(missing)}")

    out = [
        "// Code generated by gen_tables.py; DO NOT EDIT.",
        "//",
        "// 来源：LSEG Real-Time-SDK, Cpp-C/Eta/Impl/Codec/rsslcnvtab.c",
        "// 上游 commit: 7d219a600",
        "// Copyright (C) 2018-2019,2024 LSEG. All rights reserved.",
        "// Licensed under the Apache License, Version 2.0.",
        "// 机械转写：每个 uint16 与 C 表逐项一致（rssl_uni_map_entry = unsigned short）。",
        "",
        "package rmtes",
        "",
    ]
    for cname in EXPECTED:
        gname = GO_NAMES[cname]
        vals = tables[cname]
        out.append(f"// {gname} 源自 C 表 {cname}（{len(vals)} 项）。")
        out.append(f"var {gname} = [...]uint16{{")
        for i in range(0, len(vals), 8):
            chunk = ", ".join(f"0x{v:04X}" for v in vals[i : i + 8])
            out.append("\t" + chunk + ",")
        out.append("}")
        out.append("")

    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tables.go")
    with open(target, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print(f"wrote {target} ({sum(EXPECTED.values())} entries)")


if __name__ == "__main__":
    main()
